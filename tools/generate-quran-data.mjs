import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const textPath = '/tmp/quran-uthmani.txt';
const metadataPath = '/tmp/quran-data.xml';
const outputPath = resolve(root, 'src/web/src/app/data/quran-data.ts');

const quranText = await readFile(textPath, 'utf8');
const metadataXml = await readFile(metadataPath, 'utf8');

const attr = (line, name) => {
  const match = line.match(new RegExp(`${name}="([^"]*)"`));
  return match?.[1] ?? '';
};

const surahs = metadataXml
  .split(/\r?\n/)
  .filter((line) => line.includes('<sura '))
  .map((line) => ({
    number: Number(attr(line, 'index')),
    ayahCount: Number(attr(line, 'ayas')),
    startIndex: Number(attr(line, 'start')),
    name: attr(line, 'name'),
    transliteration: attr(line, 'tname'),
    englishName: attr(line, 'ename'),
    revelationType: attr(line, 'type'),
  }));

const juzStarts = metadataXml
  .split(/\r?\n/)
  .filter((line) => line.includes('<juz '))
  .map((line) => ({
    juz: Number(attr(line, 'index')),
    surah: Number(attr(line, 'sura')),
    ayah: Number(attr(line, 'aya')),
  }));

const quarterStarts = metadataXml
  .split(/\r?\n/)
  .filter((line) => line.includes('<quarter '))
  .map((line) => ({
    quarter: Number(attr(line, 'index')),
    surah: Number(attr(line, 'sura')),
    ayah: Number(attr(line, 'aya')),
  }));

const globalIndexByKey = new Map();
const verses = quranText
  .split(/\r?\n/)
  .filter((line) => /^\d+\|\d+\|/.test(line))
  .map((line, index) => {
    const [surahRaw, ayahRaw, ...textParts] = line.split('|');
    const surah = Number(surahRaw);
    const ayah = Number(ayahRaw);
    globalIndexByKey.set(`${surah}:${ayah}`, index);
    return {
      index,
      surah,
      ayah,
      juz: 1,
      quarter: 1,
      text: textParts.join('|'),
    };
  });

const juzBoundaries = juzStarts.map((start, index) => {
  const fromIndex = globalIndexByKey.get(`${start.surah}:${start.ayah}`);
  const nextStart = juzStarts[index + 1];
  const toIndex = nextStart
    ? (globalIndexByKey.get(`${nextStart.surah}:${nextStart.ayah}`) ?? verses.length) - 1
    : verses.length - 1;

  return {
    juz: start.juz,
    fromIndex,
    toIndex,
    fromSurah: start.surah,
    fromAyah: start.ayah,
  };
});

for (const boundary of juzBoundaries) {
  if (boundary.fromIndex === undefined) {
    throw new Error(`Missing juz boundary for ${boundary.juz}`);
  }

  for (let index = boundary.fromIndex; index <= boundary.toIndex; index += 1) {
    verses[index].juz = boundary.juz;
  }
}

const quarterBoundaries = quarterStarts.map((start, index) => {
  const fromIndex = globalIndexByKey.get(`${start.surah}:${start.ayah}`);
  const nextStart = quarterStarts[index + 1];
  const toIndex = nextStart
    ? (globalIndexByKey.get(`${nextStart.surah}:${nextStart.ayah}`) ?? verses.length) - 1
    : verses.length - 1;

  return {
    quarter: start.quarter,
    fromIndex,
    toIndex,
    fromSurah: start.surah,
    fromAyah: start.ayah,
  };
});

for (const boundary of quarterBoundaries) {
  if (boundary.fromIndex === undefined) {
    throw new Error(`Missing quarter boundary for ${boundary.quarter}`);
  }

  for (let index = boundary.fromIndex; index <= boundary.toIndex; index += 1) {
    verses[index].quarter = boundary.quarter;
  }
}

if (verses.length !== 6236) {
  throw new Error(`Expected 6236 verses, found ${verses.length}`);
}

const banner = `// Generated by tools/generate-quran-data.mjs from Tanzil Uthmani Quran text.
// Source: https://tanzil.net/download/ - Quran text version 1.1.
// Text is included verbatim; Tanzil requires source attribution and a link to tanzil.net.
`;

const body = `${banner}
export interface QuranVerse {
  index: number;
  surah: number;
  ayah: number;
  juz: number;
  quarter: number;
  text: string;
}

export interface SurahInfo {
  number: number;
  ayahCount: number;
  startIndex: number;
  name: string;
  transliteration: string;
  englishName: string;
  revelationType: string;
}

export interface JuzBoundary {
  juz: number;
  fromIndex: number;
  toIndex: number;
  fromSurah: number;
  fromAyah: number;
}

export interface QuarterBoundary {
  quarter: number;
  fromIndex: number;
  toIndex: number;
  fromSurah: number;
  fromAyah: number;
}

export const QURAN_SOURCE = {
  name: 'Tanzil Project Uthmani Quran Text',
  version: '1.1',
  url: 'https://tanzil.net/download/',
  metadataUrl: 'https://tanzil.net/docs/quran_metadata',
} as const;

export const SURAHS: SurahInfo[] = ${JSON.stringify(surahs, null, 2)};

export const JUZ_BOUNDARIES: JuzBoundary[] = ${JSON.stringify(juzBoundaries, null, 2)};

export const QUARTER_BOUNDARIES: QuarterBoundary[] = ${JSON.stringify(quarterBoundaries, null, 2)};

export const QURAN_VERSES: QuranVerse[] = ${JSON.stringify(verses, null, 2)};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, body, 'utf8');
